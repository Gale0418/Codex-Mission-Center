#!/usr/bin/env python3
"""
Git Hook Installer for Codex Mission Center.
Installs a post-commit hook in .git/hooks/ to auto-sync MissionCenter on git commit.
"""

import os
import sys
from pathlib import Path

TOOL_MARKER = "# Auto-generated by Codex Mission Center Git Hook Installer"
POST_COMMIT_HOOK_SCRIPT = f"""#!/bin/sh
{TOOL_MARKER}
REPO_ROOT=$(git rev-parse --show-toplevel)
python3 "$REPO_ROOT/skills/mission-center/scripts/sync_mission_center.py"
python3 "$REPO_ROOT/skills/mission-center/scripts/normalize_mission_center.py"
"""

def install_git_hook(target_repo: Path = Path('.')):
    git_dir = target_repo.resolve() / ".git"
    if not git_dir.exists():
        print(f"[MissionCenter] Warning: {target_repo} is not a Git repository root (.git not found).")
        return False

    hooks_dir = git_dir / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)

    hook_file = hooks_dir / "post-commit"
    if hook_file.exists():
        existing_bytes = hook_file.read_bytes()
        expected_bytes = POST_COMMIT_HOOK_SCRIPT.encode("utf-8")
        if existing_bytes == expected_bytes:
            print(f"[MissionCenter] Post-commit Git Hook is already installed at {hook_file}.")
            return True
        try:
            existing_text = existing_bytes.decode("utf-8")
        except UnicodeDecodeError:
            existing_text = ""
        if TOOL_MARKER not in existing_text:
            print(f"[MissionCenter] Refusing to overwrite existing hook: {hook_file}")
            return False

    hook_file.write_bytes(POST_COMMIT_HOOK_SCRIPT.encode("utf-8"))

    # Make executable on Unix
    if sys.platform != "win32":
        hook_file.chmod(0o755)

    print(f"[MissionCenter] Post-commit Git Hook successfully installed to {hook_file}!")
    return True

if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('.')
    raise SystemExit(0 if install_git_hook(target) else 1)
